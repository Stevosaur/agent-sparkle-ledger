import Link from "next/link";
import { RefreshCw } from "lucide-react";
import { requireApp } from "@/lib/auth/session";
import { latestForecast } from "@/lib/agents/demand";
import { getMarket } from "@/lib/services/market";
import { deliveryDateFor } from "@/lib/domain/time";
import { Card, CardHeader, CardBody } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { AiMark, Empty, PageHeader, Stat } from "@/components/ui/misc";
import { Table, THead, TH, TR, TD } from "@/components/ui/table";
import { ActionButton } from "@/components/app/action-button";
import { runForecastAction } from "@/app/actions";
import { kg, kgNum, date, dateTime, titleCase } from "@/lib/format";
import { cn } from "@/lib/utils";
import { OverrideForecast } from "./override-form";

export const metadata = { title: "Demand Forecast" };

const num = (v: unknown) => (v === null || v === undefined || v === "" ? null : Number(v));

const COMPONENT_LABELS: Record<string, string> = {
  sameWeekdayAvgKg: "Same-weekday avg",
  trendPct: "2-week trend",
  stockKg: "Carry-over stock",
  recommendedKg: "Recommended buy",
};
const fmtComponent = (k: string, v: number | string) => (typeof v === "number" ? (k.endsWith("Pct") ? `${v > 0 ? "+" : ""}${v}%` : k.endsWith("Kg") ? kg(v) : String(v)) : titleCase(String(v)));

/** Low–high confidence band with markers on a shared scale. */
function RangeBar({ low, high, forecast, confirmed, adjusted, max }: { low: number; high: number; forecast: number; confirmed: number | null; adjusted: number | null; max: number }) {
  const p = (v: number) => `${Math.max(0, Math.min(100, (v / max) * 100))}%`;
  return (
    <div className="relative h-5">
      <div className="absolute inset-x-0 top-1/2 h-1 -translate-y-1/2 rounded-full bg-panel-3" />
      <div className="absolute top-1/2 h-2.5 -translate-y-1/2 rounded-sm bg-info/35 ring-1 ring-info/60" style={{ left: p(low), width: `calc(${p(high)} - ${p(low)})` }} title={`80% range ${low.toFixed(1)}–${high.toFixed(1)} kg`} />
      <div className="absolute top-0 h-5 w-0.5 -translate-x-1/2 bg-text" style={{ left: p(forecast) }} title={`Forecast ${forecast.toFixed(1)} kg`} />
      {adjusted !== null && Math.abs(adjusted - forecast) > 0.05 && <div className="absolute top-0 h-5 w-0.5 -translate-x-1/2 bg-surplus" style={{ left: p(adjusted) }} title={`With overrides ${adjusted.toFixed(1)} kg`} />}
      {confirmed !== null && confirmed > 0 && <div className="absolute top-1/2 size-2.5 -translate-x-1/2 -translate-y-1/2 rotate-45 border border-bg bg-accent" style={{ left: p(confirmed) }} title={`Confirmed orders ${confirmed.toFixed(1)} kg`} />}
    </div>
  );
}

export default async function ForecastPage({ searchParams }: { searchParams: Promise<{ species?: string }> }) {
  const app = await requireApp("demand.view");
  const { species: speciesFilter } = await searchParams;
  const buyerOnly = app.role === "BUYER" ? app.membership.customerId ?? "none" : null;
  const canWrite = app.can("demand.write");
  const [fc, market] = await Promise.all([latestForecast(app.org.id, app.marketDate), buyerOnly ? Promise.resolve([]) : getMarket(app.org.id, app.marketDate)]);
  const target = deliveryDateFor(app.marketDate);

  const header = (
    <PageHeader
      eyebrow={<span className="flex items-center gap-2"><AiMark /> Demand Forecast Agent · delivery {date(target)}</span>}
      title="Demand Forecast"
      subtitle="Transparent forecast of what buyers will need for tomorrow morning's deliveries. Every number is explainable, and you can override any buyer line with a reason."
      actions={canWrite ? <ActionButton variant="primary" action={runForecastAction} data-testid="rerun-forecast"><RefreshCw /> Re-run forecast</ActionButton> : undefined}
    />
  );

  if (!fc) {
    return (
      <div>
        {header}
        <Empty title="No forecast has been generated for tonight yet">
          {canWrite ? "Run the forecast to predict buyer demand from sales history, standing orders, trend and wastage." : "The forecast is generated by the procurement team at market open."}
        </Empty>
      </div>
    );
  }

  const lines = fc.lines.filter((x) => x.l.orgId === app.org.id);
  const buyerLines = lines.filter((x) => x.l.customerId && (!buyerOnly || x.l.customerId === buyerOnly));
  const rollups = buyerOnly ? [] : lines.filter((x) => !x.l.customerId).sort((a, b) => Number(b.l.forecastKg) - Number(a.l.forecastKg));
  const confirmedBy = new Map(market.map((m) => [m.speciesId, m.demandKg]));
  const adjustedBy = new Map<string, number>();
  for (const x of buyerLines) adjustedBy.set(x.sp.id, (adjustedBy.get(x.sp.id) ?? 0) + Number(x.l.overrideKg ?? x.l.forecastKg));
  const maxKg = Math.max(1, ...rollups.map((r) => Math.max(Number(r.l.highKg), confirmedBy.get(r.sp.id) ?? 0, adjustedBy.get(r.sp.id) ?? 0))) * 1.08;

  const speciesList = [...new Map(buyerLines.map((x) => [x.sp.id, x.sp.canonicalName])).entries()].sort((a, b) => a[1].localeCompare(b[1]));
  const activeSpecies = speciesFilter && speciesList.some(([id]) => id === speciesFilter) ? speciesFilter : null;
  const tableLines = buyerLines
    .filter((x) => !activeSpecies || x.sp.id === activeSpecies)
    .sort((a, b) => a.sp.canonicalName.localeCompare(b.sp.canonicalName) || Number(b.l.forecastKg) - Number(a.l.forecastKg));

  const totalFc = rollups.reduce((a, r) => a + Number(r.l.forecastKg), 0);
  const totalRec = rollups.reduce((a, r) => a + Number(r.l.components.recommendedKg ?? 0), 0);
  const overrides = buyerLines.filter((x) => x.l.overrideKg !== null).length;

  return (
    <div>
      {header}

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Forecast demand" value={kg(buyerOnly ? buyerLines.reduce((a, x) => a + Number(x.l.forecastKg), 0) : totalFc, 0)} sub={`${rollups.length || speciesList.length} species`} />
        {!buyerOnly && <Stat label="Recommended buy" value={kg(totalRec, 0)} sub="forecast less carry-over stock" tone="ai" />}
        <Stat label="Buyer lines" value={buyerLines.length} sub={`${new Set(buyerLines.map((x) => x.l.customerId)).size} buyers`} />
        <Stat label="Overrides" value={overrides} sub={overrides ? "human-adjusted lines" : "none yet"} tone={overrides ? "surplus" : undefined} />
      </div>

      <Card className="mt-4">
        <CardBody className="flex flex-col gap-2 py-3 text-xs sm:flex-row sm:items-center sm:justify-between">
          <div className="text-muted"><span className="font-semibold uppercase tracking-wide text-text-2">Method</span> · {fc.fc.method}</div>
          <div className="num text-muted">Generated {dateTime(fc.fc.generatedAt)}</div>
        </CardBody>
      </Card>

      {rollups.length > 0 && (
        <>
          <div className="mt-5 mb-2 flex flex-wrap items-center justify-between gap-2">
            <h2 className="text-xs font-semibold uppercase tracking-wide text-muted">By species</h2>
            <div className="flex flex-wrap gap-3 text-[11px] text-muted">
              <span className="flex items-center gap-1.5"><span className="h-2.5 w-5 rounded-sm bg-info/35 ring-1 ring-info/60" /> 80% range</span>
              <span className="flex items-center gap-1.5"><span className="h-3 w-0.5 bg-text" /> forecast</span>
              <span className="flex items-center gap-1.5"><span className="h-3 w-0.5 bg-surplus" /> with overrides</span>
              <span className="flex items-center gap-1.5"><span className="size-2 rotate-45 bg-accent" /> confirmed orders</span>
            </div>
          </div>
          <div className="grid gap-3 md:grid-cols-2 2xl:grid-cols-3" data-testid="forecast-species">
            {rollups.map((r) => {
              const f = Number(r.l.forecastKg);
              const lo = Number(r.l.lowKg);
              const hi = Number(r.l.highKg);
              const conf = confirmedBy.get(r.sp.id) ?? null;
              const adj = adjustedBy.get(r.sp.id) ?? null;
              const [headline, ...rest] = r.l.explanation.split("\n");
              return (
                <Card key={r.l.id} className="flex flex-col">
                  <div className="flex items-start justify-between gap-3 px-4 pt-4">
                    <div className="min-w-0">
                      <Link href={`/demand/forecast?species=${r.sp.id}#buyers`} className="text-sm font-semibold text-text hover:text-accent">{r.sp.canonicalName}</Link>
                      {r.sp.localNames[0] && <div className="text-[11px] text-muted">{r.sp.localNames[0]}</div>}
                    </div>
                    <div className="text-right">
                      <div className="num text-2xl font-semibold text-text">{kgNum(f, 0)}<span className="ml-1 text-sm text-muted">kg</span></div>
                      <div className="num text-[11px] text-muted">{kgNum(lo, 0)}–{kgNum(hi, 0)} kg</div>
                    </div>
                  </div>
                  <div className="px-4 pt-2">
                    <RangeBar low={lo} high={hi} forecast={f} confirmed={conf} adjusted={adj} max={maxKg} />
                    <div className="num mt-0.5 flex justify-between text-[10px] text-muted">
                      <span>0</span>
                      <span>{conf !== null && conf > 0 ? `${kgNum(conf, 0)} kg confirmed` : "no orders yet"}{adj !== null && Math.abs(adj - f) > 0.05 ? ` · ${kgNum(adj, 0)} kg w/ overrides` : ""}</span>
                    </div>
                  </div>
                  <div className="mx-4 mt-3 rounded-lg bg-panel-2 p-3">
                    <div className="flex items-center gap-2 text-[13px] font-semibold text-text"><AiMark />{headline}</div>
                    {rest.length > 0 && <div className="mt-1.5 space-y-0.5 text-xs leading-relaxed text-text-2">{rest.map((ln, i) => <p key={i} className={cn(/^why:?$/i.test(ln.trim()) && "font-semibold text-muted")}>{ln}</p>)}</div>}
                  </div>
                  <div className="mt-auto flex flex-wrap gap-1.5 px-4 py-3">
                    {Object.entries(r.l.components).map(([k, v]) => (
                      <span key={k} className="rounded border border-border px-1.5 py-0.5 text-[11px] text-muted">
                        {COMPONENT_LABELS[k] ?? titleCase(k.replace(/([A-Z])/g, "_$1"))} <span className="num text-text-2">{fmtComponent(k, v)}</span>
                      </span>
                    ))}
                  </div>
                </Card>
              );
            })}
          </div>
        </>
      )}

      <Card className="mt-5" id="buyers">
        <CardHeader
          title="Per-buyer forecast"
          subtitle={canWrite ? "Override a line when you know something the history doesn't (banquets, closures, holidays). A reason is required." : "Forecast by buyer and species."}
        />
        {speciesList.length > 1 && (
          <div className="flex flex-wrap gap-1.5 border-b border-border px-4 py-2.5">
            <Link href="/demand/forecast#buyers" className={cn("rounded-md border px-2.5 py-1 text-xs", !activeSpecies ? "border-accent bg-accent-soft text-accent" : "border-border text-text-2 hover:bg-panel-2")}>All</Link>
            {speciesList.map(([id, name]) => (
              <Link key={id} href={`/demand/forecast?species=${id}#buyers`} className={cn("rounded-md border px-2.5 py-1 text-xs", activeSpecies === id ? "border-accent bg-accent-soft text-accent" : "border-border text-text-2 hover:bg-panel-2")}>{name}</Link>
            ))}
          </div>
        )}
        {tableLines.length === 0 ? (
          <CardBody><Empty title="No buyer-level forecast lines" /></CardBody>
        ) : (
          <Table className="min-w-[860px]">
            <THead>
              <tr>
                <TH>Buyer</TH>
                <TH>Species</TH>
                <TH align="right">Forecast</TH>
                <TH align="right">80% range</TH>
                <TH>Drivers</TH>
                <TH align="right">Override</TH>
                {canWrite && <TH />}
              </tr>
            </THead>
            <tbody>
              {tableLines.map(({ l, sp, c }) => {
                const comp = l.components as Record<string, number | string>;
                const reason = l.explanation.includes(": ") ? l.explanation.slice(l.explanation.indexOf(": ") + 2) : l.explanation;
                const ov = num(l.overrideKg);
                return (
                  <TR key={l.id}>
                    <TD className="align-top">
                      <div className="font-medium text-text">{c?.name ?? "—"}</div>
                      {c?.priorityTier === 1 && <Badge tone="spike" className="mt-0.5">Priority</Badge>}
                    </TD>
                    <TD className="align-top text-text-2">{sp.canonicalName}</TD>
                    <TD num className={cn("align-top font-semibold", ov !== null ? "text-muted line-through" : "text-text")}>{kgNum(l.forecastKg)}</TD>
                    <TD num className="align-top text-muted">{kgNum(l.lowKg)}–{kgNum(l.highKg)}</TD>
                    <TD className="max-w-[340px] align-top">
                      <p className="text-xs leading-relaxed text-muted">{reason}</p>
                      <div className="mt-1 flex flex-wrap gap-1">
                        {comp.standingOrderKg ? <Badge tone="info" mono>standing {kgNum(comp.standingOrderKg)} kg</Badge> : null}
                        {comp.method ? <Badge mono>{titleCase(String(comp.method))}</Badge> : null}
                        {typeof comp.trendPct === "number" && comp.trendPct !== 0 ? <Badge tone={comp.trendPct > 0 ? "ok" : "late"} mono>trend {comp.trendPct > 0 ? "+" : ""}{comp.trendPct}%</Badge> : null}
                      </div>
                    </TD>
                    <TD num className="align-top">
                      {ov !== null ? (
                        <div>
                          <div className="font-semibold text-surplus">{kgNum(ov)} kg</div>
                          <div className="mt-0.5 max-w-[220px] text-left font-sans text-[11px] text-muted sm:text-right">“{l.overrideReason}” — {l.overrideBy}</div>
                        </div>
                      ) : (
                        <span className="text-muted">—</span>
                      )}
                    </TD>
                    {canWrite && (
                      <TD className="align-top text-right">
                        <OverrideForecast lineId={l.id} label={`${c?.name ?? "Buyer"} · ${sp.canonicalName}`} forecastKg={Number(l.forecastKg)} lowKg={Number(l.lowKg)} highKg={Number(l.highKg)} currentOverride={ov} />
                      </TD>
                    )}
                  </TR>
                );
              })}
            </tbody>
          </Table>
        )}
      </Card>
    </div>
  );
}
